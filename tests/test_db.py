"""The database layer: the same SQL has to behave the same on SQLite and on PostgreSQL.

These run on whichever backend the suite runs on (SQLite by default, PostgreSQL with
TEST_DATABASE_URL), so each assertion is checked against both.
"""
import pytest

from testbench import db, storage, users
from .conftest import sqlite_only


